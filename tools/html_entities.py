#!/usr/bin/env python3
# Writes sgcl/txt/detail/html_entities.h: the named character references of
# the WHATWG HTML standard (section 13.5), 2231 names with and without their
# semicolon, as Python's html.entities.html5 holds that table. Run from the
# root of the tree:
#
#   python3 tools/html_entities.py
import html.entities

HEADER = """//------------------------------------------------------------------------------
// SGCL: a C++20 application platform
// Copyright (c) 2022-2026 Sebastian Nibisz
// SPDX-License-Identifier: Apache-2.0
//------------------------------------------------------------------------------
"""

items = sorted(html.entities.html5.items())
lines = [HEADER, "#pragma once", "", "#include <cstdint>", "#include <string_view>", "",
         "// The named character references of HTML (WHATWG HTML 13.5), sorted by name:",
         "// a name (its semicolon included where the table has one) and the one or two",
         "// code points it stands for. Generated by tools/html_entities.py: do not edit.",
         "namespace sgcl::txt::detail::html {",
         "    struct NamedReference {",
         "        std::string_view name;",
         "        char32_t first;",
         "        char32_t second;",
         "    };",
         "",
         "    inline constexpr NamedReference NamedReferences[] = {"]
for name, value in items:
    cps = [ord(c) for c in value]
    second = cps[1] if len(cps) > 1 else 0
    lines.append('        {"%s", 0x%X, 0x%X},' % (name, cps[0], second))
lines += ["    };", "}", ""]
with open("sgcl/txt/detail/html_entities.h", "w") as f:
    f.write("\n".join(lines))
print(len(items))

"""sgcl/codec/detail/qr_kanji.h: the characters QR's Kanji mode holds.

Kanji mode (ISO/IEC 18004, 7.4.6) writes a character as its Shift JIS code,
two bytes in 0x8140-0x9FFC or 0xE040-0xEBBF, packed into 13 bits. The table
is every code point of the Basic Multilingual Plane whose Shift JIS (JIS X
0208, as Python's shift_jis codec maps it) falls in those ranges, sorted by
code point, each with its 13-bit value: the data of the mapping, nothing of
any library's code.

    python3 tools/gen_qr_kanji.py > sgcl/codec/detail/qr_kanji.h
"""

pairs = []
for cp in range(0x80, 0x10000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    try:
        b = chr(cp).encode('shift_jis')
    except UnicodeEncodeError:
        continue
    if len(b) != 2:
        continue
    v = b[0] << 8 | b[1]
    if 0x8140 <= v <= 0x9FFC:
        v -= 0x8140
    elif 0xE040 <= v <= 0xEBBF:
        v -= 0xC140
    else:
        continue
    pairs.append((cp, (v >> 8) * 0xC0 + (v & 0xFF)))

out = []
out.append('''//------------------------------------------------------------------------------
// SGCL: a C++20 application platform
// Copyright (c) 2022-2026 Sebastian Nibisz
// SPDX-License-Identifier: Apache-2.0
//------------------------------------------------------------------------------
// Generated by tools/gen_qr_kanji.py: do not edit.
#pragma once

#include <cstdint>

// The characters QR's Kanji mode holds (ISO/IEC 18004, 7.4.6): code points
// of JIS X 0208 whose Shift JIS falls in 0x8140-0x9FFC or 0xE040-0xEBBF,
// sorted, each with its 13-bit value, %d of them.
namespace sgcl::codec::detail {
    struct QrKanji {
        uint16_t code_point;
        uint16_t value;
    };

    inline constexpr QrKanji QrKanjiTable[] = {''' % len(pairs))
line = '       '
for cp, v in pairs:
    item = ' {0x%04X, %d},' % (cp, v)
    if len(line) + len(item) > 118:
        out.append(line)
        line = '       '
    line += item
out.append(line)
out.append('''    };
}''')
print('\n'.join(out))

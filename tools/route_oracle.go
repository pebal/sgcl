// The oracle for the routes of sgcl/net/http/server.h: Go's ServeMux (Go
// 1.22 patterns) asked the same questions, its answers written out as a
// C++ header the test includes. Run it from the root of the tree:
//
//	go run tools/route_oracle.go > tests/net/http/route_oracle.h
//
// Two kinds of question, each case named below:
//
//   - pairs of patterns: whether the second, registered after the first,
//     conflicts (ServeMux panics);
//   - one table of patterns that do not conflict, and requests (method,
//     host, path) against it: the pattern that serves each, or 404, or 405
//     with the methods of Allow, or 301 with its Location. The paths are
//     clean: the module routes the path the URL parser normalized, where
//     ServeMux cleans and redirects, which is not asked.
package main

import (
	"fmt"
	"net/http"
	"net/http/httptest"
	"sort"
	"strings"
)

func lit(s string) string {
	return fmt.Sprintf("%q", s)
}

func conflicts(a, b string) (c bool) {
	mux := http.NewServeMux()
	mux.HandleFunc(a, func(http.ResponseWriter, *http.Request) {})
	defer func() {
		if recover() != nil {
			c = true
		}
	}()
	mux.HandleFunc(b, func(http.ResponseWriter, *http.Request) {})
	return false
}


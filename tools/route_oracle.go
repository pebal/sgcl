func serve(table []string, requests [][3]string) {
	mux := http.NewServeMux()
	for _, p := range table {
		pattern := p
		mux.HandleFunc(pattern, func(w http.ResponseWriter, r *http.Request) {
			var names []string
			for _, seg := range strings.Split(pattern, "/") {
				if strings.HasPrefix(seg, "{") && seg != "{$}" {
					names = append(names, strings.TrimSuffix(strings.Trim(seg, "{}"), "..."))
				}
			}
			var values []string
			for _, n := range names {
				values = append(values, n+"="+r.PathValue(n))
			}
			w.Header().Set("X-Pattern", pattern)
			w.Header().Set("X-Values", strings.Join(values, "&"))
		})
	}
	for _, q := range requests {
		r := httptest.NewRequest(q[0], "http://"+q[1]+q[2], nil)
		r.Host = q[1]
		w := httptest.NewRecorder()
		mux.ServeHTTP(w, r)
		allow := strings.Split(w.Header().Get("Allow"), ", ")
		sort.Strings(allow)
		fmt.Printf("    {%s, %s, %s, %d, %s, %s, %s, %s},\n", lit(q[0]), lit(q[1]), lit(q[2]), w.Code, lit(w.Header().Get("X-Pattern")),
			lit(w.Header().Get("X-Values")), lit(strings.Join(allow, ", ")), lit(w.Header().Get("Location")))
	}
}

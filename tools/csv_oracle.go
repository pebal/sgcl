// The oracle for the CSV of sgcl/encoding (csv.h): Go's encoding/csv asked
// the same questions, the answers written out as a C++ header the tests
// include. Run it from benchmarks/go (where go.mod is):
//
//     go run ../../tools/csv_oracle.go > ../../tests/encoding/csv_tests.h
//
// What is asked, by name:
//
//   - texts read with the options of the reader (separator, comment,
//     lazy quotes, trimmed leading space, the same field count or not):
//     the records before the error, each field with its line and column
//     (FieldPos), and the error — its kind, its line and column; the
//     texts are the cases RFC 4180 and Go's documentation name (quotes,
//     "" inside, line endings inside quotes, CRLF, a lone CR, empty lines,
//     comments, a bare quote, a character after a closing quote, a quote
//     not closed, fields of other counts, a BOM, trailing separators);
//   - records written, with '\n' and with CRLF, with another separator;
//   - a hundred thousand random texts of the characters that matter
//     (",;\"\n\r #\t" and letters), read with four sets of options, as a
//     hash of what Go reads (the records and the error's kind and line);
//     generated by splitmix64, which the test writes the same way.
//
// The column Go gives is the byte of the line; the reader here counts
// code points. The texts here are ASCII, where the two are the same.
package main

import (
	"bytes"
	"encoding/csv"
	"errors"
	"fmt"
	"io"
	"os"
	"strings"
)

type rng struct{ state uint64 }

func (r *rng) next() uint64 {
	r.state += 0x9E3779B97F4A7C15
	z := r.state
	z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9
	z = (z ^ (z >> 27)) * 0x94D049BB133111EB
	return z ^ (z >> 31)
}

func quote(b []byte) string {
	var sb strings.Builder
	sb.WriteByte('"')
	for _, c := range b {
		if c == '"' || c == '\\' {
			sb.WriteByte('\\')
			sb.WriteByte(c)
		} else if c >= 0x20 && c < 0x7F && c != '?' {
			sb.WriteByte(c)
		} else {
			fmt.Fprintf(&sb, "\\x%02x\"\"", c)
		}
	}
	sb.WriteByte('"')
	return sb.String()
}

type opts struct {
	comma, comment rune
	lazy, trim     bool
	fields         int
}

// What Go reads of a text: the records, a line each, fields as
// <line:column>text separated by \x1f; then the error, if any, as
// !kind line:column (kind: bare, quote, count)
func read(text string, o opts) string {
	r := csv.NewReader(strings.NewReader(text))
	r.Comma = o.comma
	r.Comment = o.comment
	r.LazyQuotes = o.lazy
	r.TrimLeadingSpace = o.trim
	r.FieldsPerRecord = o.fields
	var out strings.Builder
	for {
		rec, err := r.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			var pe *csv.ParseError
			if !errors.As(err, &pe) {
				panic(err)
			}
			kind := "?"
			switch {
			case errors.Is(pe.Err, csv.ErrBareQuote):
				kind = "bare"
			case errors.Is(pe.Err, csv.ErrQuote):
				kind = "quote"
			case errors.Is(pe.Err, csv.ErrFieldCount):
				kind = "count"
			}
			if kind == "count" {
				// Go gives the record with this error; the reader here stops
				fmt.Fprintf(&out, "!%s %d:%d\n", kind, pe.StartLine, pe.Column)
			} else {
				fmt.Fprintf(&out, "!%s %d:%d\n", kind, pe.Line, pe.Column)
			}
			break
		}
		for i, f := range rec {
			if i > 0 {
				out.WriteByte('\x1f')
			}
			line, col := r.FieldPos(i)
			fmt.Fprintf(&out, "<%d:%d>%s", line, col, f)
		}
		out.WriteByte('\n')
	}
	return out.String()
}

func main() {
	w := os.Stdout
	fmt.Fprintln(w, "// Generated by tools/csv_oracle.go (Go's encoding/csv): do not edit.")
	fmt.Fprintln(w, "#pragma once")
	fmt.Fprintln(w, "#include <cstdint>")
	fmt.Fprintln(w, "#include <string_view>")
	fmt.Fprintln(w, "namespace csv_oracle {")
	fmt.Fprintln(w, "struct read_case { std::string_view text; char separator; char comment; bool lazy; bool trim; bool same_count; std::string_view read; };")
	fmt.Fprintln(w, "inline constexpr read_case reads[] = {")
	std := opts{comma: ',', fields: 0}
	variable := opts{comma: ',', fields: -1}
	cases := []struct {
		text string
		o    opts
	}{
		{"a,b,c\n", std},
		{"a,b,c", std},
		{"a,b,c\r\n1,2,3\r\n", std},
		{"\"a\",\"b,c\",\"d\"\"e\"\n", std},
		{"\"multi\nline\",x\n", std},
		{"\"multi\r\nline\",x\r\n", std},
		{"a\rb,c\n", std},
		{"a,b\r", std},
		{"a,b\n\n\nc,d\n", std},
		{"a,b\n\r\nc,d\n", std},
		{"\n\n", std},
		{"", std},
		{"a,,b,\n,,,\n", variable},
		{"a,\"\",b\n", std},
		{"a,b\"c,d\n", std},
		{"a,b\"c,d\n", opts{comma: ',', lazy: true}},
		{"\"a\"b,c\n", std},
		{"\"a\"b,c\n", opts{comma: ',', lazy: true}},
		{"\"abc\n", std},
		{"\"abc\n", opts{comma: ',', lazy: true}},
		{"a,\"b\nc", std},
		{"a,b\nc\n", std},
		{"a,b\nc\n", variable},
		{"a,b\nc,d,e\n", std},
		{"# comment\na,b\n#x,y\nc,d\n", opts{comma: ',', comment: '#'}},
		{"a;b;c\n1;\"2;3\";4\n", opts{comma: ';'}},
		{"a\tb\n", opts{comma: '\t'}},
		{"  a,  \"b\",\tc\n", opts{comma: ',', trim: true}},
		{"  a,  \"b\",\tc\n", std},
		{"\xef\xbb\xbfa,b\n", std},
		{"a,\"b\"\"\",c\n", std},
		{"\"\"\"\"\n", std},
		{"x,\"a\"\"b\nc\"\"d\",y\nz,w,v\n", std},
		{"a,\"b\" ,c\n", std},
		{"a,\"b\" ,c\n", opts{comma: ',', lazy: true}},
		{"a,b,\n", std},
		{",\n", std},
		{"\"\n\"\n", std},
		{"a,b\n  \n", variable},
		{"#only\n", opts{comma: ',', comment: '#'}},
		{"a\"\n", opts{comma: ',', lazy: true}},
		{"\"a\"\"\n", std},
		{"\"a\"\"\n", opts{comma: ',', lazy: true}},
		{"\\.,x\n", std},
		{"a,b\r\r\nc,d\n", std},
		{"\"a\r\"\n", std},
	}
	for _, c := range cases {
		fmt.Fprintf(w, "    {%s, '%s', '%s', %v, %v, %v, %s},\n", quote([]byte(c.text)), escapeChar(c.o.comma), escapeChar(c.o.comment), c.o.lazy, c.o.trim, c.o.fields == 0, quote([]byte(read(c.text, c.o))))
	}
	fmt.Fprintln(w, "};")

	// --- written ---
	fmt.Fprintln(w, "struct write_case { std::string_view fields; char separator; bool crlf; std::string_view text; };   // fields split by \\x1f, records by \\x1e")
	fmt.Fprintln(w, "inline constexpr write_case writes[] = {")
	records := [][]string{{"a", "b", "c"}, {"", "x", ""}, {"with,comma", "with\"quote", "with\nline", "with\r\nboth"}, {" leading", "\tleading", "trailing ", `\.`}, {"é", "a;b", "\u00a0x"}}
	for _, crlf := range []bool{false, true} {
		for _, comma := range []rune{',', ';'} {
			var buf bytes.Buffer
			cw := csv.NewWriter(&buf)
			cw.Comma = comma
			cw.UseCRLF = crlf
			var in strings.Builder
			for i, rec := range records {
				if i > 0 {
					in.WriteByte('\x1e')
				}
				in.WriteString(strings.Join(rec, "\x1f"))
				if err := cw.Write(rec); err != nil {
					panic(err)
				}
			}
			cw.Flush()
			fmt.Fprintf(w, "    {%s, '%c', %v, %s},\n", quote([]byte(in.String())), comma, crlf, quote(buf.Bytes()))
		}
	}
	fmt.Fprintln(w, "};")

	// --- random texts ---
	alphabet := []byte(",;\"\n\r #\tab")
	sets := []opts{std, variable, {comma: ';', comment: '#', fields: -1}, {comma: ',', lazy: true, trim: true, fields: -1}}
	r := &rng{2026}
	h := uint64(0xcbf29ce484222325)
	for i := 0; i < 100000; i++ {
		n := int(r.next() % 24)
		b := make([]byte, n)
		for k := range b {
			b[k] = alphabet[r.next()%uint64(len(alphabet))]
		}
		o := sets[i%len(sets)]
		for _, c := range []byte(read(string(b), o)) {
			h ^= uint64(c)
			h *= 0x100000001b3
		}
	}
	fmt.Fprintf(w, "inline constexpr uint64_t random_hash = 0x%016xull;   // 100000 texts, seed 2026\n", h)
	fmt.Fprintln(w, "}")
}

func escapeChar(c rune) string {
	switch c {
	case 0:
		return "\\0"
	case '\t':
		return "\\t"
	case '\'':
		return "\\'"
	}
	return string(c)
}

// The oracles for sgcl/net/url.h, written out as a C++ header the test
// includes. Run it from the root of the tree, with the web platform tests'
// URL data downloaded to ~/Programming/oracles/wpt-url:
//
//     go run tools/url_oracle.go ~/Programming/oracles/wpt-url > tests/net/url_oracle.h
//
// Two oracles, of different weight:
//
//   - The WHATWG URL Standard's own test data, whole, from
//     web-platform-tests/url/resources: urltestdata.json (every input,
//     with or without a base: whether it parses, and then href, origin,
//     protocol, username, password, host, hostname, port, pathname,
//     search, hash), setters_tests.json (every setter: the URL before, the
//     value, and the parts after) and toascii.json (a host through the
//     host parser: the ASCII it becomes, or failure). The JSON is copied
//     into C++ literals, nothing decided here.
//
//   - Go's net/url, a different standard (RFC 3986, read loosely), asked
//     only where the two agree, each case named below: the examples of
//     RFC 3986 §5.4 resolved against its base (ResolveReference), the
//     parts of plain absolute URLs (Parse), and the pairs of queries
//     (ParseQuery) made of an alphabet both read the same way (no ';', no
//     broken escape, no invalid UTF-8, where Go refuses and the standard
//     does not).
package main

import (
	"encoding/json"
	"fmt"
	"math/rand"
	"net/url"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func lit(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '?':
			b.WriteString("\\?") // no trigraphs
		case c >= 0x20 && c < 0x7f:
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\%03o", c)
		}
	}
	b.WriteString("\"sv")
	return b.String()
}

func field(m map[string]any, k string) (string, bool) {
	v, ok := m[k]
	if !ok || v == nil {
		return "", false
	}
	s, ok := v.(string)
	return s, ok
}

func load(dir, name string, v any) {
	data, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		panic(err)
	}
	if err := json.Unmarshal(data, v); err != nil {
		panic(err)
	}
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: go run tools/url_oracle.go <dir of the WPT url resources>")
		os.Exit(2)
	}
	dir := os.Args[1]
	w := os.Stdout
	fmt.Fprintln(w, "// Generated by tools/url_oracle.go from the web platform tests' URL data")
	fmt.Fprintln(w, "// (url/resources: urltestdata.json, setters_tests.json, toascii.json) and")
	fmt.Fprintln(w, "// Go's net/url. Do not edit.")
	fmt.Fprintln(w, "#pragma once")
	fmt.Fprintln(w, "#include <string_view>")
	fmt.Fprintln(w, "namespace url_oracle {")
	fmt.Fprintln(w, "using namespace std::string_view_literals;")

	// urltestdata.json
	var parse []any
	load(dir, "urltestdata.json", &parse)
	fmt.Fprintln(w, "struct Parse { std::string_view input; bool has_base; std::string_view base; bool failure;")
	fmt.Fprintln(w, "    std::string_view href, origin, protocol, username, password, host, hostname, port, pathname, search, hash; bool has_origin; };")
	fmt.Fprintln(w, "inline const Parse parse_cases[] = {")
	for _, x := range parse {
		m, ok := x.(map[string]any)
		if !ok {
			continue
		}
		input, _ := field(m, "input")
		base, hasBase := field(m, "base")
		failure := m["failure"] == true
		get := func(k string) string { s, _ := field(m, k); return s }
		_, hasOrigin := field(m, "origin")
		fmt.Fprintf(w, "    {%s, %v, %s, %v, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %v},\n",
			lit(input), hasBase, lit(base), failure, lit(get("href")), lit(get("origin")), lit(get("protocol")),
			lit(get("username")), lit(get("password")), lit(get("host")), lit(get("hostname")), lit(get("port")),
			lit(get("pathname")), lit(get("search")), lit(get("hash")), hasOrigin)
	}
	fmt.Fprintln(w, "};")

	// setters_tests.json
	var setters map[string]any
	load(dir, "setters_tests.json", &setters)
	fmt.Fprintln(w, "struct Setter { std::string_view setter, href, value;")
	fmt.Fprintln(w, "    // the parts expected after it; a part the test does not name is absent")
	fmt.Fprintln(w, "    std::string_view expected[10]; bool named[10]; };")
	fmt.Fprintln(w, "// the order of expected[]: href, protocol, username, password, host, hostname, port, pathname, search, hash")
	parts := []string{"href", "protocol", "username", "password", "host", "hostname", "port", "pathname", "search", "hash"}
	var names []string
	for k := range setters {
		if k != "comment" {
			names = append(names, k)
		}
	}
	sort.Strings(names)
	fmt.Fprintln(w, "inline const Setter setter_cases[] = {")
	for _, k := range names {
		for _, x := range setters[k].([]any) {
			m := x.(map[string]any)
			href, _ := field(m, "href")
			value, _ := field(m, "new_value")
			exp := m["expected"].(map[string]any)
			var e, n []string
			for _, p := range parts {
				s, ok := field(exp, p)
				e = append(e, lit(s))
				n = append(n, fmt.Sprint(ok))
			}
			fmt.Fprintf(w, "    {%s, %s, %s, {%s}, {%s}},\n", lit(k), lit(href), lit(value), strings.Join(e, ", "), strings.Join(n, ", "))
		}
	}
	fmt.Fprintln(w, "};")

	// toascii.json
	var toascii []any
	load(dir, "toascii.json", &toascii)
	fmt.Fprintln(w, "struct ToAscii { std::string_view input; bool failure; std::string_view output; };")
	fmt.Fprintln(w, "inline const ToAscii toascii_cases[] = {")
	for _, x := range toascii {
		m, ok := x.(map[string]any)
		if !ok {
			continue
		}
		input, _ := field(m, "input")
		out, has := field(m, "output")
		fmt.Fprintf(w, "    {%s, %v, %s},\n", lit(input), !has, lit(out))
	}
	fmt.Fprintln(w, "};")

	// Go: RFC 3986 §5.4.1 and §5.4.2 against the base http://a/b/c/d;p?q,
	// every example; the test names the one where the two standards
	// part ("//g": http://g/ in the URL Standard, whose special URL has
	// the path "/", and http://g in RFC 3986). "http:g", which they also
	// part on, is not asked.
	refs := []string{
		"g:h", "g", "./g", "g/", "/g", "//g", "?y", "g?y", "#s", "g#s", "g?y#s", ";x", "g;x", "g;x?y#s", "", ".", "./",
		"..", "../", "../g", "../..", "../../", "../../g",
		"../../../g", "../../../../g", "/./g", "/../g", "g.", ".g", "g..", "..g", "./../g", "./g/.", "g/./h", "g/../h",
		"g;x=1/./y", "g;x=1/../y", "g?y/./x", "g?y/../x", "g#s/./x", "g#s/../x",
	}
	base, _ := url.Parse("http://a/b/c/d;p?q")
	fmt.Fprintln(w, "struct Resolve { std::string_view reference, go; };")
	fmt.Fprintln(w, "inline constexpr std::string_view resolve_base = \"http://a/b/c/d;p?q\"sv;")
	fmt.Fprintln(w, "inline const Resolve resolve_cases[] = {")
	for _, r := range refs {
		ref, err := url.Parse(r)
		if err != nil {
			panic(err)
		}
		fmt.Fprintf(w, "    {%s, %s},\n", lit(r), lit(base.ResolveReference(ref).String()))
	}
	fmt.Fprintln(w, "};")

	// Go: plain absolute URLs, where the two parsers agree part for part
	plain := []string{
		"http://example.com/", "http://example.com/a/b/c", "https://example.com:8443/x?y=1#z",
		"http://user:pass@example.com:8080/p?q#f", "http://user@example.com/", "http://[::1]:8080/",
		"http://[2001:db8::1]/a", "http://10.0.0.1:81/", "ws://example.com/chat", "wss://example.com:9443/",
		"ftp://ftp.example.com/pub/file.txt", "http://example.com/a%20b", "http://example.com/?a=1&b=2",
		"http://example.com/#frag", "http://example.com/a/b/", "https://a.b.c.example.com/x/y/z?k=v&k=w#top",
		"http://example.com/%7Euser/", "http://example.com:1/", "http://example.com:65535/", "https://xn--bcher-kva.de/",
	}
	fmt.Fprintln(w, "struct Plain { std::string_view input, scheme, username, password, hostname, port, path, query, fragment; };")
	fmt.Fprintln(w, "inline const Plain plain_cases[] = {")
	for _, s := range plain {
		u, err := url.Parse(s)
		if err != nil {
			panic(err)
		}
		pw, _ := u.User.Password()
		fmt.Fprintf(w, "    {%s, %s, %s, %s, %s, %s, %s, %s, %s},\n", lit(s), lit(u.Scheme), lit(u.User.Username()), lit(pw),
			lit(u.Hostname()), lit(u.Port()), lit(u.EscapedPath()), lit(u.RawQuery), lit(u.EscapedFragment()))
	}
	fmt.Fprintln(w, "};")

	// Go: queries of an alphabet both read alike, random, a fixed seed;
	// each case the pairs Go finds, as name, value, name, value..., grouped
	// by name in the order of first appearance (Go's Values is a map; its
	// values of one name are in order, which is what is compared)
	rng := rand.New(rand.NewSource(20260925))
	atoms := []string{"a", "b", "c", "=", "&", "&", "+", "%20", "%41", "%C3%A9", "\xc3\xa9", "%26", "%3D", "%2B", "x", "-", "_", ".", "~", "*"}
	fmt.Fprintln(w, "struct Query { std::string_view input; std::string_view pairs[64]; int count; };")
	fmt.Fprintln(w, "inline const Query query_cases[] = {")
	for i := 0; i < 400; i++ {
		var b strings.Builder
		n := 1 + rng.Intn(12)
		for j := 0; j < n; j++ {
			b.WriteString(atoms[rng.Intn(len(atoms))])
		}
		q := b.String()
		v, err := url.ParseQuery(q)
		if err != nil {
			panic(err)
		}
		var order []string
		seen := map[string]bool{}
		for _, piece := range strings.Split(q, "&") {
			if piece == "" {
				continue
			}
			k := piece
			if eq := strings.IndexByte(piece, '='); eq >= 0 {
				k = piece[:eq]
			}
			key, _ := url.QueryUnescape(k)
			if !seen[key] {
				seen[key] = true
				order = append(order, key)
			}
		}
		var out []string
		for _, k := range order {
			for _, val := range v[k] {
				out = append(out, lit(k), lit(val))
			}
		}
		if len(out) > 64 {
			continue
		}
		fmt.Fprintf(w, "    {%s, {%s}, %d},\n", lit(q), strings.Join(out, ", "), len(out))
	}
	fmt.Fprintln(w, "};")
	fmt.Fprintln(w, "}")
}

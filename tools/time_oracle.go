func tzifOf(rule string, std string, offset int) []byte {
	var b []byte
	u32 := func(v uint32) { b = append(b, byte(v>>24), byte(v>>16), byte(v>>8), byte(v)) }
	header := func() {
		b = append(b, 'T', 'Z', 'i', 'f', '2')
		b = append(b, make([]byte, 15)...)
		u32(0)                    // isutcnt
		u32(0)                    // isstdcnt
		u32(0)                    // leapcnt
		u32(0)                    // timecnt
		u32(1)                    // typecnt
		u32(uint32(len(std) + 1)) // charcnt
	}
	block := func() {
		u32(uint32(int32(offset)))
		b = append(b, 0, 0)
		b = append(b, std...)
		b = append(b, 0)
	}
	header()
	block()
	header()
	block()
	b = append(b, '\n')
	b = append(b, rule...)
	b = append(b, '\n')
	return b
}

type zoneState struct {
	off  int
	dst  bool
	abbr string
}

func stateAt(t time.Time) zoneState {
	name, off := t.Zone()
	return zoneState{off, t.IsDST(), name}
}

func zones() {
	root := "/usr/share/zoneinfo/"
	version, err := os.ReadFile(root + "+VERSION")
	if err != nil {
		panic(err)
	}
	var names []string
	var walk func(prefix string)
	walk = func(prefix string) {
		entries, err := os.ReadDir(root + prefix)
		if err != nil {
			panic(err)
		}
		for _, e := range entries {
			n := e.Name()
			full := n
			if prefix != "" {
				full = prefix + "/" + n
			}
			if e.IsDir() {
				if prefix == "" && (n == "posix" || n == "right") {
					continue
				}
				walk(full)
				continue
			}
			if n == "posixrules" || n == "localtime" {
				continue
			}
			data, err := os.ReadFile(root + full)
			if err != nil || len(data) < 4 || string(data[:4]) != "TZif" {
				continue
			}
			names = append(names, full)
		}
	}
	walk("")
	sort.Strings(names)

	abbrs := map[string]int{}
	var abbrList []string
	abbr := func(s string) int {
		if i, ok := abbrs[s]; ok {
			return i
		}
		abbrs[s] = len(abbrList)
		abbrList = append(abbrList, s)
		return abbrs[s]
	}
	var changes, samples []string
	var cases []string
	runs := map[string]int{}
	rng := rand.New(rand.NewSource(20260925))
	lo := time.Date(1700, 1, 1, 0, 0, 0, 0, time.UTC).Unix()
	hi := time.Date(2400, 1, 1, 0, 0, 0, 0, time.UTC).Unix()
	state := func(s zoneState) string {
		return fmt.Sprintf("{%d, %t, %d}", s.off, s.dst, abbr(s.abbr))
	}
	ask := func(name string, loc *time.Location, from time.Time) string {
		lo := lo
		if from.Year() >= 1970 {
			lo = from.Unix()
		}
		limit := time.Date(2101, 1, 1, 0, 0, 0, 0, time.UTC)
		t := from.In(loc)
		prev := stateAt(t)
		var mine []string
		for {
			_, end := t.ZoneBounds()
			if end.IsZero() || !end.Before(limit) {
				break
			}
			if !end.After(t) {
				// ZoneBounds standing still: a period of no length, which
				// Go gives for the rules of daylight saving time all
				// year; the walk steps over it by a second
				end = t.Add(time.Second)
			}
			if stateAt(end.Add(-time.Second).In(loc)) != prev {
				// ZoneBounds says the period lasts to `end` and Zone()
				// says it ended before: Go disagrees with itself, and
				// nothing written from here could be trusted
				panic(fmt.Sprintf("%s: ZoneBounds from %v ends at %v, past a change", name, t.UTC(), end.UTC()))
			}
			t = end.In(loc)
			s := stateAt(t)
			if s == prev {
				continue
			}
			mine = append(mine, fmt.Sprintf("{%d, %s}", end.Unix(), state(s)))
			prev = s
		}
		// A link of the database (Poland, Europe/Warsaw) has the changes
		// of its target: kept once, and both cases point at them
		key := strings.Join(mine, ";")
		first, seen := runs[key]
		if !seen {
			first = len(changes)
			runs[key] = first
			changes = append(changes, mine...)
		}
		firstSample := len(samples)
		for i := 0; i < 20; i++ {
			at := lo + rng.Int63n(hi-lo)
			samples = append(samples, fmt.Sprintf("{%d, %s}", at, state(stateAt(time.Unix(at, 0).In(loc)))))
		}
		before := stateAt(time.Date(1600, 1, 1, 0, 0, 0, 0, time.UTC).In(loc))
		return fmt.Sprintf("{%q, %s, %s, %d, %d, %d, %d}", name, state(before), state(stateAt(from.In(loc))),
			first, len(mine), firstSample, len(samples)-firstSample)
	}
	for _, name := range names {
		loc, err := time.LoadLocation(name)
		if err != nil {
			panic(err)
		}
		cases = append(cases, ask(name, loc, time.Date(1800, 1, 1, 0, 0, 0, 0, time.UTC)))
	}
	var rules []string
	for _, r := range posixRules {
		// The standard name and offset, for the one type of the file:
		// what Go's own reading of the rule says at a time of standard
		// time is not asked, the file is built from the text
		std, off := posixStd(r.rule)
		loc, err := time.LoadLocationFromTZData(r.rule, tzifOf(r.rule, std, off))
		if err != nil {
			panic(err)
		}
		rules = append(rules, ask(r.rule, loc, time.Date(1970, 1, 1, 0, 0, 0, 0, time.UTC)))
	}

	fmt.Println("//------------------------------------------------------------------------------")
	fmt.Println("// SGCL: a C++20 application framework")
	fmt.Println("// Copyright (c) 2022-2026 Sebastian Nibisz")
	fmt.Println("// SPDX-License-Identifier: Apache-2.0")
	fmt.Println("//------------------------------------------------------------------------------")
	fmt.Println("#pragma once")
	fmt.Println()
	fmt.Println("// Generated by tools/time_oracle.go zones: do not edit.")
	fmt.Println("//")
	fmt.Println("// What Go's time package answers about the zones of the system's")
	fmt.Println("// database and about POSIX TZ strings; the program says what is asked.")
	fmt.Println()
	fmt.Println("#include <cstdint>")
	fmt.Println()
	fmt.Println("namespace oracle {")
	fmt.Printf("    inline constexpr const char* ZoneVersion = %q;\n\n", strings.TrimSpace(string(version)))
	fmt.Println("    struct ZoneState {")
	fmt.Println("        int32_t offset;")
	fmt.Println("        bool dst;")
	fmt.Println("        uint16_t abbreviation;   // into ZoneAbbreviations")
	fmt.Println("    };")
	fmt.Println()
	fmt.Println("    struct ZoneChange {")
	fmt.Println("        int64_t at;              // seconds since 1970 UTC")
	fmt.Println("        ZoneState to;")
	fmt.Println("    };")
	fmt.Println()
	fmt.Println("    struct ZoneCase {")
	fmt.Println("        const char* name;")
	fmt.Println("        ZoneState before_all;    // at 1600-01-01: Go's lookupFirstZone")
	fmt.Println("        ZoneState from;          // at 1800-01-01 (1970 for a rule)")
	fmt.Println("        uint32_t first_change, changes;")
	fmt.Println("        uint32_t first_sample, samples;")
	fmt.Println("    };")
	fmt.Println()
	fmt.Println("    inline constexpr const char* ZoneAbbreviations[] = {")
	for _, a := range abbrList {
		fmt.Printf("        %q,\n", a)
	}
	fmt.Println("    };")
	fmt.Println()
	fmt.Println("    // every change to the end of 2100, zone after zone")
	fmt.Println("    inline constexpr ZoneChange ZoneChanges[] = {")
	for _, c := range changes {
		fmt.Printf("        %s,\n", c)
	}
	fmt.Println("    };")
	fmt.Println()
	fmt.Println("    // the zone at instants from 1700 to 2400")
	fmt.Println("    inline constexpr ZoneChange ZoneSamples[] = {")
	for _, c := range samples {
		fmt.Printf("        %s,\n", c)
	}
	fmt.Println("    };")
	fmt.Println()
	fmt.Println("    inline constexpr ZoneCase Zones[] = {")
	for _, c := range cases {
		fmt.Printf("        %s,\n", c)
	}
	fmt.Println("    };")
	fmt.Println()
	fmt.Println("    // POSIX TZ strings in a TZif file with no transition (tools/time_oracle.go says why each)")
	fmt.Println("    inline constexpr ZoneCase PosixRules[] = {")
	for i, c := range rules {
		fmt.Printf("        %s,   // %s\n", c, posixRules[i].why)
	}
	fmt.Println("    };")
	fmt.Println("}")
}

// The standard name and offset (seconds east) at the head of a TZ string
func posixStd(rule string) (string, int) {
	i := 0
	var name string
	if rule[0] == '<' {
		j := strings.IndexByte(rule, '>')
		name = rule[1:j]
		i = j + 1
	} else {
		for i < len(rule) && (rule[i] >= 'A' && rule[i] <= 'Z' || rule[i] >= 'a' && rule[i] <= 'z') {
			i++
		}
		name = rule[:i]
	}
	sign := -1
	if rule[i] == '-' {
		sign = 1
		i++
	} else if rule[i] == '+' {
		i++
	}
	parts := []int{0, 0, 0}
	k := 0
	for i < len(rule) && k < 3 {
		if rule[i] == ':' {
			k++
			i++
			continue
		}
		if rule[i] < '0' || rule[i] > '9' {
			break
		}
		parts[k] = parts[k]*10 + int(rule[i]-'0')
		i++
	}
	return name, sign * (parts[0]*3600 + parts[1]*60 + parts[2])
}

// The text of instants (text_cases.h):
//
//   - written: t.Format(time.RFC3339), t.Format(time.RFC3339Nano),
//     t.UTC().Format(http.TimeFormat) and t.Format(time.RFC1123Z) at
//     instants drawn over the whole range and at the edges of dtInstants,

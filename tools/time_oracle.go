// Every instant showing a time of the clock: the offsets the zone has
// within 26 hours of it, each tried
func instantsOf(y, m, d, h, mi, s int, loc *time.Location) []int64 {
	wall := time.Date(y, time.Month(m), d, h, mi, s, 0, time.UTC).Unix()
	seen := map[int]bool{}
	var out []int64
	for k := -26 * 4; k <= 26*4; k++ {
		_, off := time.Unix(wall+int64(k)*900, 0).In(loc).Zone()
		if seen[off] {
			continue
		}
		seen[off] = true
		t := wall - int64(off)
		if _, o := time.Unix(t, 0).In(loc).Zone(); o == off {
			out = append(out, t)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i] < out[j] })
	return out
}

func isoWeekdayOf(t time.Time) int {
	w := int(t.Weekday())
	if w == 0 {
		return 7
	}
	return w
}


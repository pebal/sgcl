// The zones (zone_cases.h). Every zone of the system's database, found
// as sgcl's zone::available() finds them (the files under
// /usr/share/zoneinfo that start with "TZif", posix/ and right/ and
// posixrules left out), loaded with time.LoadLocation, which reads the
// same files, and asked:
//
//   - the zone at 1800-01-01T00:00:00Z (offset, abbreviation, isDST),
//     then every change from there to the end of 2100 by walking
//     t.ZoneBounds(), a change that alters none of the three not
//     counted (sgcl drops those entries); the changes of a link are
//     those of its target, written once;
//   - the zone at 20 instants drawn from 1700 to 2400, the years past
//     2100 being the POSIX rule's in both;
//   - the zone at 1600-01-01T00:00:00Z, before every zone's first
//     transition: RFC 9636 says type 0, Go's lookupFirstZone picks a
//     type by its own rules; the test compares and names the zones where
//     they differ instead of bending either.
//
// And POSIX TZ strings alone (PosixRules below, each named for what it
// tries): a TZif file of version 2 is built with no transition, one type
// and the string as its footer, which Go and RFC 9636 both read as the
// rule for all time (Go adds a transition at the beginning of time to
// make it so), and asked the same questions over 1970 to 2100 and at
// instants from 1970 to 2400. Two places where Go 1.27 is wrong are left
// out and checked by hand in the test instead:
//
//   - every time before 1970, where a change by the rule comes a day
//     late (for CET-1CEST,M3.5.0,M10.5.0/3 Go says CET at noon UTC of the
//     last Sunday of March in each of the years 1700 to 1969, CEST from
//     1970 on): the second of the day is taken as the remainder of a
//     negative number, which is negative; the zones of the database are
//     not touched by it, their tables covering those years;
//   - daylight saving time all year (RFC 9636 3.3.1,
//     "EST5EDT,0/0,J365/25"), where Go gives standard time for the hours
//     between New Year in UTC and New Year at the standard offset (EST
//     from 00:00Z to 05:00Z every January 1); the RFC and the C library
//     (TZ=... date) say EDT throughout.
//
// The version of the database goes in the header; the test skips when
// the system has another one.

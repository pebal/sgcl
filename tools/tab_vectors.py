#!/usr/bin/env python3
# The vectors of tests/txt/tab_writer.cpp: random tables (words, empty cells,
# soft tabs, form feeds, escapes, HTML, letters past ASCII of one column) with
# random options, written whole and in random pieces, answered by Go's
# text/tabwriter (tools/tab_oracle.go) and by the library
# (tools/tab_driver.cpp, which checks that a tab_writer fed the pieces writes
# what align_tabs writes). Prints a summary on stderr and the vectors where
# the two agree on stdout:
#
#   tools/tab_vectors.py <tab_driver> <tab_oracle> > tests/txt/tab_vectors.h
import os
import random
import subprocess
import sys

R = random.Random(int(os.environ.get("SEED", "20261006")))
DRIVER, ORACLE = sys.argv[1], sys.argv[2]
N = int(os.environ.get("N", "1000"))

WORDS = [w.encode() for w in ["a", "bb", "ccc", "name", "size", "1204", "", "", "zażółć", "Ελλάδα", "x y",
                               "<b>bold</b>", "&amp;", "a&lt;b", "&broken", "<tag", "  pad  ", "ü", "ДА"]] + \
        [b"\xffesc\taped\xff", b"\xff\xff", b"\xffopen"]   # the escape byte
FLAGS = [1, 2, 4, 8, 16, 32]


def table():
    lines = []
    for _ in range(R.randint(0, 8)):
        cells = [R.choice(WORDS) for _ in range(R.randint(0, 5))]
        seps = [R.choice([b"\t", b"\t", b"\t", b"\v"]) for _ in cells]
        line = b"".join(c + s for c, s in zip(cells, seps))
        if R.random() < 0.7:
            line += R.choice(WORDS)
        lines.append(line + R.choice([b"\n", b"\n", b"\n", b"\n", b"\f"]))
    t = b"".join(lines)
    if R.random() < 0.3:
        t += R.choice(WORDS) + R.choice([b"", b"\t", b"\tz"])
    return t


cases = []
for _ in range(N):
    text = table()
    flags = 0
    for f in FLAGS:
        if R.random() < 0.25:
            flags |= f
    pad = R.choice([ord(" "), ord(" "), ord("."), ord("\t"), ord("-")])
    o = (R.choice([0, 0, 1, 4, 10]), R.choice([8, 8, 4, 1, 0]), R.choice([1, 1, 0, 2, 3]), pad, flags)
    if len(text) > 1 and R.random() < 0.6:
        cuts = sorted(R.sample(range(1, len(text)), min(len(text) - 1, R.randint(1, 5))))
        pieces = ",".join(str(b - a) for a, b in zip([0] + cuts, cuts))
    else:
        pieces = "-"
    cases.append((o, text, pieces))

q = "".join("%d %d %d %d %d %s %s\n" % (o + (t.hex() or "-", p)) for o, t, p in cases)
go = subprocess.run([ORACLE], input=q.encode(), capture_output=True, check=True).stdout.decode().split("\n")
us = subprocess.run([DRIVER], input=q.encode(), capture_output=True, check=True).stdout.decode().split("\n")

agree = []
differ = mismatch = 0
for (o, t, p), g, u in zip(cases, go, us):
    if u == "MISMATCH":
        mismatch += 1
        sys.stderr.write("tab_writer in pieces %s differs from align_tabs: %r %r\n" % (p, o, t))
        continue
    if g == u:
        agree.append((o, t, bytes.fromhex(g)))
    else:
        differ += 1
        if differ <= 10:
            sys.stderr.write("differs from Go: %r %r\n--- go\n%r\n--- us\n%r\n" % (o, t, bytes.fromhex(g), bytes.fromhex(u)))


def c_literal(b):
    out = ['"']
    for ch in b:
        if ch == 0x22:
            out.append('\\"')
        elif ch == 0x5C:
            out.append("\\\\")
        elif 0x20 <= ch < 0x7F and ch != 0x3F:
            out.append(chr(ch))
        else:
            out.append("\\%03o" % ch)
    out.append('"')
    return "".join(out)


print("//------------------------------------------------------------------------------")
print("// SGCL: a C++20 application platform")
print("// Copyright (c) 2022-2026 Sebastian Nibisz")
print("// SPDX-License-Identifier: Apache-2.0")
print("//------------------------------------------------------------------------------")
print("// Generated by tools/tab_vectors.py: do not edit. Tables aligned by Go's")
print("// text/tabwriter; flags: FilterHTML 1, StripEscape 2, AlignRight 4,")
print("// DiscardEmptyColumns 8, TabIndent 16, Debug 32.")
print("#pragma once")
print()
print("#include <cstddef>")
print()
print("struct TabVector {")
print("    size_t min_width, tab_width, padding;")
print("    char pad_char;")
print("    unsigned flags;")
print("    const char* text;")
print("    size_t text_size;")
print("    const char* result;")
print("    size_t result_size;")
print("};")
print()
print("inline const TabVector TabVectors[] = {")
for o, t, r in agree:
    print("    {%d, %d, %d, %d, %d, %s, %d, %s, %d}," % (o[0], o[1], o[2], o[3], o[4], c_literal(t), len(t), c_literal(r), len(r)))
print("};")
sys.stderr.write("%d agree with Go, %d differ; %d streamed differently\n" % (len(agree), differ, mismatch))
